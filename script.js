/* ============================================================
   BACK TO TOP
   ============================================================ */

window.addEventListener('scroll', function() {
  const backToTop = document.getElementById('back-to-top');

  if (!backToTop) return;

  backToTop.classList.toggle(
    'show',
    window.scrollY > 420
  );
});


