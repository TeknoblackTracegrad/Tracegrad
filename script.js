/* ============================================================
   TRACEGRAD LANDING PAGE NAVIGATION
   ============================================================ */

const LSEC_DISPLAY = {
  home: 'flex',
  about: 'block',
  gallery: 'block',
  devs: 'block'
};

const LNK_MAP = {
  home: 'lnk-home',
  about: 'lnk-about',
  gallery: 'lnk-gallery',
  devs: 'lnk-devs'
};

function showSection(id, btn, updateHash = true) {
  const target = document.getElementById('lsec-' + id);

  if (!target) return;

  // Hide all sections
  document.querySelectorAll('.lsec').forEach(function(sec) {
    sec.classList.remove('on');
    sec.style.display = 'none';
  });

  // Show selected section
  target.classList.add('on');
  target.style.display = LSEC_DISPLAY[id] || 'block';

  // Update navigation active state
  document.querySelectorAll('.lnav-link').forEach(function(link) {
    link.classList.remove('on');
  });

  const activeLink =
    btn || document.getElementById(LNK_MAP[id]);

  if (activeLink) {
    activeLink.classList.add('on');
  }

  // Update URL hash
  if (updateHash && window.history && history.pushState) {
    history.pushState(
      { section: id },
      '',
      '#' + id
    );
  }

  // Scroll to top
  window.scrollTo({
    top: 0,
    left: 0,
    behavior: 'smooth'
  });
}


/* ============================================================
   BROWSER BACK / FORWARD SUPPORT
   ============================================================ */

window.addEventListener('popstate', function() {
  const id = window.location.hash
    .replace('#', '')
    .toLowerCase();

  const valid = [
    'home',
    'about',
    'gallery',
    'devs'
  ];

  showSection(
    valid.includes(id) ? id : 'home',
    null,
    false
  );
});


