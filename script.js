  /* ==========================================================
     FALLBACK RESPONSE
     ========================================================== */

  const FALLBACK = function() {
    return `I'm not sure about that one yet — I only handle common questions about signing in, account activation, the CHED survey, and the photo gallery. For anything else, please contact the ISUFST Alumni Affairs Office or your College/Department Admin.`;
  };


  /* ==========================================================
     MATCH USER MESSAGE TO INTENT
     ========================================================== */

  function matchIntent(raw) {

    const text = raw.toLowerCase();

    for (const intent of INTENTS) {

      if (
        intent.patterns.some(function(pattern) {
          return text.includes(pattern);
        })
      ) {
        return intent;
      }

    }

    return null;
  }


  /* ==========================================================
     MESSAGE TIME
     ========================================================== */

  function nowLabel() {

    return new Date().toLocaleTimeString([], {
      hour: '2-digit',
      minute: '2-digit'
    });

  }


  /* ==========================================================
     ESCAPE HTML
     ========================================================== */

  function escapeHTML(text) {

    const div = document.createElement('div');

    div.textContent = text;

    return div.innerHTML;
  }


  /* ==========================================================
     RENDER CHAT MESSAGE
     ========================================================== */

  function renderMessage(role, text) {

    const wrap = document.getElementById('chat-msgs');

    if (!wrap) return;

    const row = document.createElement('div');

    row.className = 'chat-msg ' + role;

    const safeText = escapeHTML(text);

    row.innerHTML =
      (role === 'bot'
        ? '<div class="chat-msg-av">TG</div>'
        : '') +

      '<div class="chat-bubble">' +
        safeText +
        '<span class="chat-msg-time">' +
          nowLabel() +
        '</span>' +
      '</div>';

    wrap.appendChild(row);

    wrap.scrollTop = wrap.scrollHeight;
  }


  /* ==========================================================
     SHOW TYPING INDICATOR
     ========================================================== */

  function showTyping() {

    const wrap = document.getElementById('chat-msgs');

    if (!wrap) return;

    const row = document.createElement('div');

    row.className = 'chat-msg bot';

    row.id = 'chat-typing-row';

    row.innerHTML =
      '<div class="chat-msg-av">TG</div>' +
      '<div class="chat-typing">' +
        '<span></span>' +
        '<span></span>' +
        '<span></span>' +
      '</div>';

    wrap.appendChild(row);

    wrap.scrollTop = wrap.scrollHeight;
  }


  /* ==========================================================
     HIDE TYPING INDICATOR
     ========================================================== */

  function hideTyping() {

    const row =
      document.getElementById('chat-typing-row');

    if (row) {
      row.remove();
    }
  }


  /* ==========================================================
     BOT RESPONSE
     ========================================================== */

  function respondTo(userText) {

    showTyping();

    window.setTimeout(function() {

      hideTyping();

      const intent = matchIntent(userText);

      const reply =
        intent
          ? intent.response()
          : FALLBACK();

      chatHistory.push({
        role: 'bot',
        text: reply,
        intent: intent
          ? intent.name
          : 'fallback'
      });

      renderMessage(
        'bot',
        reply
      );

    }, 500 + Math.random() * 400);
  }


  /* ==========================================================
     SEND CHAT MESSAGE
     ========================================================== */

  window.sendChat = function() {

    const input =
      document.getElementById('chat-input');

    if (!input) return;

    const text =
      input.value.trim();

    if (!text) return;

    chatHistory.push({
      role: 'user',
      text: text
    });

    renderMessage(
      'user',
      text
    );

    input.value = '';

    respondTo(text);
  };


  /* ==========================================================
     QUICK CHAT BUTTON
     ========================================================== */

  window.sendQuick = function(text) {

    const box =
      document.getElementById('chatbot-box');

    if (box) {
      box.classList.add('open');
    }

    chatHistory.push({
      role: 'user',
      text: text
    });

    renderMessage(
      'user',
      text
    );

    respondTo(text);
  };


  /* ==========================================================
     TOGGLE CHATBOT
     ========================================================== */

  window.toggleChatbot = function(force) {

    const box =
      document.getElementById('chatbot-box');

    if (!box) return;

    const open =
      typeof force === 'boolean'
        ? force
        : !box.classList.contains('open');

    box.classList.toggle(
      'open',
      open
    );

    /*
     * Greet the visitor only the first time
     * the chatbot is opened.
     */
    if (open && !hasGreeted) {

      hasGreeted = true;

      respondTo('hello');
    }

    if (open) {

      const input =
        document.getElementById('chat-input');

      if (input) {
        input.focus();
      }
    }
  };

